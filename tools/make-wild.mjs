// Generate the 150 Wild Ponds (design: three blocks of 50 with rising
// difficulty), each verified by the solver, and write game/src/wild.js.
import { writeFileSync } from 'node:fs';
import { generateCandidate } from '../game/src/generator.js';
import { solve, randomWinRate, mulberry32 } from '../game/src/solver.js';

const BLOCKS = [
  { from: 1, to: 50, sizes: [6], pads: [8, 10], types: 1, band: [0.3, 0.6], area: 'morning' },
  { from: 51, to: 100, sizes: [7], pads: [10, 13], types: 2, band: [0.1, 0.25], area: 'sunset' },
  { from: 101, to: 150, sizes: [7, 8], pads: [12, 16], types: 3, band: [0.03, 0.12], area: 'moon' },
];
const NAMES = ['Dewdrop', 'Mossy', 'Ripple', 'Willow', 'Pebble', 'Clover', 'Minnow', 'Fern', 'Puddle', 'Breeze',
  'Sunny', 'Lily', 'Cattail', 'Drizzle', 'Glimmer', 'Hazel', 'Meadow', 'Sprout', 'Tadpole', 'Whisper'];

function cfgFor(block, rng) {
  const size = block.sizes[Math.floor(rng() * block.sizes.length)];
  const pads = block.pads[0] + Math.floor(rng() * (block.pads[1] - block.pads[0] + 1));
  const kinds = ['turtle', 'beetle', 'fish'].sort(() => rng() - 0.5).slice(0, Math.floor(rng() * (block.types + 1)));
  const cfg = { w: size, h: size, pads, pSink: 0.5 + rng() * 0.3, reeds: 2 + Math.floor(rng() * 3) };
  if (kinds.includes('turtle')) { cfg.turtles = 1 + (block.types > 2 && rng() < 0.4 ? 1 : 0); }
  if (kinds.includes('beetle')) { cfg.beetles = 1 + (block.types > 1 && rng() < 0.4 ? 1 : 0); }
  if (kinds.includes('fish')) { cfg.fish = 1; cfg.fishGives = [rng() < 0.5 ? 'mend' : 'leap']; }
  return cfg;
}

const rng = mulberry32(20261023);
const out = [];
const t0 = Date.now();
for (const block of BLOCKS) {
  const ponds = [];
  for (let n = block.from; n <= block.to; n++) {
    let best = null;
    const start = Date.now();
    while (Date.now() - start < 4000) {
      const cfg = cfgFor(block, rng);
      const r = generateCandidate(cfg, rng);
      if (r.fail) continue;
      if (solve(r.level).solvable !== true) continue;
      const rate = randomWinRate(r.level, rng, 300);
      const [lo, hi] = block.band;
      const score = rate >= lo && rate <= hi ? 0 : Math.abs(rate - (lo + hi) / 2);
      if (!best || score < best.score) best = { L: r.level, rate, score };
      if (score === 0) break;
    }
    if (!best) { console.log('pond', n, 'none'); continue; }
    const L = best.L;
    ponds.push({
      name: NAMES[n % NAMES.length] + ' Pond', area: block.area, w: L.w, h: L.h,
      pads: L.pads, turtles: L.turtles, beetles: L.beetles, fish: L.fish, reeds: L.reeds,
      hint: '', solution: L.solution, rate: Math.round(best.rate * 1000) / 1000,
    });
  }
  ponds.sort((a, b) => b.rate - a.rate);
  out.push(...ponds);
  console.log(`block ${block.from}-${block.to}: ${ponds.length} ponds, rates ${ponds[0].rate}..${ponds[ponds.length - 1].rate}, ${((Date.now() - t0) / 1000).toFixed(0)} s`);
}
writeFileSync(new URL('../game/src/wild.js', import.meta.url),
  '// Generated by tools/make-wild.mjs; verified by tools/verify-levels.mjs.\nexport const WILD = ' + JSON.stringify(out) + ';\n');
console.log('wrote', out.length, 'ponds');
